package com.joysistvi;

public class Activity1_Abella  {
    public static void main(String[] args) {
        // Step 2 & 3: Declare and initialize variables of different data types
        boolean isJavaFun = true;          // boolean can only be true or false
        byte age = 25;                     // byte range: -128 to 127
        short year = 2026;                 // short range: -32,768 to 32,767
        int population = 110000000;        // int for whole numbers
        long distance = 9876543210L;       // long for very large numbers
        float price = 99.99f;              // float for decimal values (single precision)
        double pi = 3.14159265359;         // double for more precise decimals
        char grade = 'A';                  // char stores a single character
        String greeting = "Hello, Java World!"; // String stores text

        // Step 4: Print out the values with labels
        System.out.println("is Javafun: " + isJavaFun + "     >>>...boolean can only be true or false");
        System.out.println("My age: " + age + "     >>>...byte range: -128 to 127");
        System.out.println("Year of Birth: " + year + "     >>>...short range: -32,768 to 32,767");
        System.out.println("Earth Population: " + population + "     >>>...int for whole numbers");
        System.out.println("Distance of Moon from Earth: " + distance + " meter" + "     >>>...long for very large numbers");
        System.out.println("Average price of Banana: " + price + "     >>>...float for decimal values (single precision)");
        System.out.println("Value of Pi: " + pi + "     >>>...ouble for more precise decimals");
        System.out.println("Final grade: " + grade + "     >>>...char stores a single character, enclose eith single quotation");
        System.out.println("Greetings: " + greeting + "     >>>...String stores text");
    }}
